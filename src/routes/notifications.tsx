import { createFileRoute, Link } from "@tanstack/react-router";
import { ArrowLeft, Bell, BellOff } from "lucide-react";
import { Button } from "@/components/ui/button";
import { Shell } from "@/components/Shell";
import { useStore } from "@/lib/store";

export const Route = createFileRoute("/notifications")({
  head: () => ({ meta: [
    { title: "Notifications — MTC Pocket Market" },
    { name: "description", content: "Review browser-local preview notifications. Live MTC alerts are not connected." },
    { property: "og:title", content: "Notifications — MTC Pocket Market" },
    { property: "og:type", content: "website" },
  ] }),
  component: Notifications,
});

export function Notifications() {
  const { notices, markAllRead } = useStore();
  const unreadCount = notices.filter((notice) => !notice.read).length;

  return <Shell>
    <div className="px-5 pb-10 pt-6">
      <Button asChild variant="secondary" size="icon" className="size-11 rounded-full bg-card shadow-none">
        <Link to="/" aria-label="Back to Home"><ArrowLeft className="size-5" /></Link>
      </Button>
      <h1 className="mt-6 text-[30px] font-bold tracking-tight">Notifications</h1>
      <p className="mt-2 text-[14px] leading-6 text-muted-foreground">
        Pocket Market does not send push alerts, SMS or live delivery notifications yet.
      </p>
      {unreadCount > 0 && <Button type="button" variant="outline" onClick={markAllRead}
        className="mt-5 min-h-11 rounded-full text-[14px] shadow-none">
        Mark {unreadCount} as read
      </Button>}

      {notices.length === 0 ? <div className="mt-7 rounded-[20px] bg-card px-5 py-10 text-center">
        <BellOff aria-hidden="true" className="mx-auto size-9 text-muted-foreground" />
        <p className="mt-3 text-[16px] font-semibold">Nothing here yet</p>
        <p className="mt-2 text-[14px] leading-6 text-muted-foreground">You'll be able to find account notifications here after a verified notification service is connected.</p>
      </div> : <section className="mt-7" aria-labelledby="archived-notices">
        <h2 id="archived-notices" className="text-[15px] font-semibold">Previous demo events</h2>
        <p className="mt-2 text-[13px] leading-5 text-muted-foreground">These events were generated by an earlier preview. They are not evidence of courier activity.</p>
        <div className="mt-4 space-y-3">
          {notices.map((notice) => <Link key={notice.key} to="/orders"
            className="flex min-h-20 items-start gap-3 rounded-[18px] border border-border bg-card p-4">
            <span className="grid size-11 shrink-0 place-items-center rounded-[14px] bg-surface-2">
              <Bell aria-hidden="true" className="size-5 text-mint" />
            </span>
            <span className="min-w-0 flex-1">
              <span className="flex items-center gap-2 text-[14px] font-semibold">
                Historical demo notification {!notice.read && <span className="inline-block size-2 rounded-full bg-brand-red" />}
              </span>
              <span className="mt-1 block text-[13px] leading-5 text-muted-foreground">Preview order {notice.orderId}, not a real delivery status.</span>
              <span className="mt-2 block text-[12px] text-muted-foreground">{new Date(notice.at).toLocaleString("en-NA")}</span>
            </span>
          </Link>)}
        </div>
      </section>}
    </div>
  </Shell>;
}
